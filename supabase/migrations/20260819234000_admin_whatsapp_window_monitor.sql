create extension if not exists pg_cron;

create table if not exists public.admin_whatsapp_window_monitor (
  admin_phone text primary key,
  last_inbound_at timestamptz not null,
  window_expires_at timestamptz not null,
  window_status text not null default 'open' check (window_status in ('open','expired')),
  warn_6h_sent_at timestamptz,
  warn_2h_sent_at timestamptz,
  warn_30m_sent_at timestamptz,
  last_warning_level text check (last_warning_level is null or last_warning_level in ('6h','2h','30m')),
  last_provider_message_id text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.admin_whatsapp_window_warning_log (
  id bigint generated by default as identity primary key,
  admin_phone text not null,
  warning_level text not null check (warning_level in ('6h','2h','30m')),
  window_expires_at timestamptz not null,
  provider_message_id text,
  sent_at timestamptz not null default now()
);

create index if not exists admin_whatsapp_window_warning_log_phone_sent_idx
  on public.admin_whatsapp_window_warning_log(admin_phone, sent_at desc);

alter table public.admin_whatsapp_window_monitor enable row level security;
alter table public.admin_whatsapp_window_warning_log enable row level security;

revoke all on public.admin_whatsapp_window_monitor from anon, authenticated;
revoke all on public.admin_whatsapp_window_warning_log from anon, authenticated;

grant all on public.admin_whatsapp_window_monitor to service_role;
grant all on public.admin_whatsapp_window_warning_log to service_role;

