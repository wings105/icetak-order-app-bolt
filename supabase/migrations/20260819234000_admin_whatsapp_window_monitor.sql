create or replace function public.icetak_check_admin_whatsapp_window()
returns bigint
language plpgsql
security definer
set search_path = 'public'
as $$
declare
  monitor_url text;
  monitor_token text;
  request_id bigint;
begin
  select setting_value into monitor_url
  from public.private_runtime_settings
  where setting_key = 'admin_whatsapp_window_monitor_url'
  limit 1;

  select setting_value into monitor_token
  from public.private_runtime_settings
  where setting_key = 'qrpay_ai_worker_token'
  limit 1;

  if nullif(monitor_url, '') is null or nullif(monitor_token, '') is null then
    return null;
  end if;

  select net.http_post(
    url := monitor_url,
    headers := jsonb_build_object(
      'content-type', 'application/json',
      'x-admin-window-token', monitor_token
    ),
    body := jsonb_build_object('action', 'check')
  ) into request_id;

  return request_id;
end;
$$;

revoke all on function public.icetak_check_admin_whatsapp_window() from public, anon, authenticated;
grant execute on function public.icetak_check_admin_whatsapp_window() to service_role;

select cron.unschedule(jobid)
from cron.job
where jobname = 'icetak-admin-whatsapp-window-every-5-minutes';

select cron.schedule(
  'icetak-admin-whatsapp-window-every-5-minutes',
  '*/5 * * * *',
  'select public.icetak_check_admin_whatsapp_window();'
);
