import assert from 'node:assert/strict';
import {assess,combinedEvidence,ORDER,SET,SKU} from './compare.ts';
const order={order_sn:'TEST_ORDER',shop_id:'test',items:[{sku:'CN0001',model:'Birthday topper'}]};
const task=(id,sku,name=sku,set=[])=>({id,name,custom_fields:[{id:ORDER,value:order.order_sn},{id:SKU,value:sku},{id:SET,value:set}]});
assert.equal(assess(order,[])[0].kind,'missing_order');
assert.equal(assess(order,[task('a','CN0001')]).length,0);
assert.equal(assess(order,[task('a','CN0001'),task('b','CN0001')])[0].kind,'extra_or_duplicate_tasks');
const two={...order,items:[{sku:'same',model:'3.5 inch Round'},{sku:'same',model:'4 inch Round'}]};
assert.equal(assess(two,[task('a','same')])[0].kind,'missing_item_or_unverified_combination');
assert.equal(combinedEvidence(two.items,[task('a','same')],['3.5 inch Round / 4 inch Round']),true);
assert.equal(assess(two,[task('a','same')],['3.5 inch Round / 4 inch Round']).length,0);
assert.equal(combinedEvidence(two.items,[task('a','same')],['same']),false);
assert.equal(assess(two,[task('a','3.5 inch Round'),task('b','4 inch Round')]).length,0);
assert.equal(assess(two,[task('a','3.5 inch Round'),task('b','3.5 inch Round')])[0].kind,'item_match_requires_review');
const set1='80bb319b-02c0-45d3-9ee1-4fcba7e3ee4b';
assert.equal(assess(two,[task('a','3.5 inch Round','',[set1]),task('b','4 inch Round','',[set1])])[0].kind,'duplicate_set');
assert.equal(assess(order,[task('a','CN0001')]).length,0);
assert.equal(assess({...order,items:[{sku:'CN0001',quantity:2}]},[task('a','CN0001','1x CN0001')])[0].kind,'quantity_mismatch');
assert.equal(assess(two,[task('a','same','3.5 inch Round'),task('b','same','3.5 inch Round')])[0].kind,'item_match_requires_review');
assert.equal(assess({...order,items:[{sku:'.',quantity:1}]},[task('a','.','5 × 5 inch, Round')]).length,0);
assert.equal(assess({...order,items:[{sku:'.',quantity:1}]},[task('a','.','6 x 6 inch, Round')]).length,0);
assert.equal(assess({...order,items:[{sku:'.',quantity:1}]},[task('a','.','5.5 × 5.5 inch')]).length,0);
console.log('16 audit comparison checks passed');
